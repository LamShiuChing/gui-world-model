export default class Tetromino {
    constructor(type) {
        this.type = type;
        this.color = TETROMINOES[type].color;
        this.orientation = 0; // 0, R, 2, L (mapped to 0, 1, 2, 3)
    }

    getBlocks(x, y, orientation) {
        const orientKey = [0, 'R', 2, 'L'][orientation];
        const offsets = TETROMINOES[this.type].offsets[orientKey];
        return offsets.map(([dx, dy]) => ({ x: x + dx, y: y + dy }));
    }

    clone() {
        const clone = new Tetromino(this.type);
        clone.orientation = this.orientation;
        return clone;
    }
}
